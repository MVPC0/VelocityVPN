// Regenerates src/data/world-land-dots.ts from Natural Earth land (world-atlas 50m).
// Dev-only: run from a scratch dir that has world-atlas, topojson-client and d3-geo installed:
//   NODE_PATH=/path/to/node_modules node scripts/gen-land-dots.mjs
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
const require = createRequire(process.env.NODE_PATH ? process.env.NODE_PATH + "/" : import.meta.url);
const topo = require("topojson-client");
const { geoContains, geoBounds } = require("d3-geo");
const world = require("world-atlas/land-50m.json");

// Keep in sync with src/lib/world-map.ts
const LON_MIN = -170, LON_MAX = 180, LAT_MAX = 76, LAT_MIN = -56;
const COLS = 200;
const STEP = (LON_MAX - LON_MIN) / COLS;
const ROWS = Math.round((LAT_MAX - LAT_MIN) / STEP);

const land = topo.feature(world, world.objects.land);
// Split into polygons with bounding boxes so each point only tests nearby polygons
const polys = (land.type === "FeatureCollection" ? land.features : [land])
  .flatMap((f) => (f.geometry.type === "MultiPolygon" ? f.geometry.coordinates : [f.geometry.coordinates]))
  .map((coordinates) => {
    const g = { type: "Polygon", coordinates };
    const [[w, s], [e, n]] = geoBounds(g);
    return { g, w, s, e, n };
  });
const isLand = (lon, lat) =>
  polys.some((p) => lat >= p.s && lat <= p.n && (p.w <= p.e ? lon >= p.w && lon <= p.e : lon >= p.w || lon <= p.e) && geoContains(p.g, [lon, lat]));
const rows = [];
let count = 0;
for (let r = 0; r < ROWS; r++) {
  let bits = "";
  for (let c = 0; c < COLS; c++) {
    const lon0 = LON_MIN + c * STEP, lat0 = LAT_MAX - r * STEP;
    // 3x3 sub-samples so small islands (UK, Japan, NZ, Indonesia) still show
    let hit = 0;
    for (const fx of [0.2, 0.5, 0.8]) for (const fy of [0.2, 0.5, 0.8])
      if (isLand(lon0 + fx * STEP, lat0 - fy * STEP)) hit++;
    const on = hit >= 2 ? 1 : 0;
    count += on;
    bits += on;
  }
  // pack 4 bits per hex char
  let hex = "";
  for (let i = 0; i < bits.length; i += 4) hex += parseInt(bits.slice(i, i + 4).padEnd(4, "0"), 2).toString(16);
  rows.push(hex);
}
const out = `// Generated by scripts/gen-land-dots.mjs from Natural Earth land (world-atlas 50m).
// Equirectangular grid, ${COLS} x ${ROWS} cells of ${STEP} deg, ${count} land cells.
// Each row is a hex bitmask (MSB first) of land cells from west to east.
export const LAND_COLS = ${COLS};
export const LAND_ROWS = ${ROWS};
export const LAND_ROWS_HEX: readonly string[] = [
${rows.map((r) => `  "${r}",`).join("\n")}
];
`;
writeFileSync(new URL("../src/data/world-land-dots.ts", import.meta.url), out);
console.log(`rows=${ROWS} cols=${COLS} land=${count}`);
